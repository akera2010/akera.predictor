// ---------------------------------------------------------------------------
// Release signing: read from environment variables. If they are missing (e.g.
// a fork without secrets) the release build falls back to the debug key so CI
// always produces an installable APK.
// ---------------------------------------------------------------------------
val releaseKeystorePath: String? = System.getenv("AKERATEN_KEYSTORE_PATH")
val releaseKeystorePassword: String? = System.getenv("AKERATEN_KEYSTORE_PASSWORD")
val releaseKeyAlias: String? = System.getenv("AKERATEN_KEY_ALIAS")
val releaseKeyPassword: String? = System.getenv("AKERATEN_KEY_PASSWORD")
val hasReleaseKeystore: Boolean =
    releaseKeystorePath?.let { it.isNotBlank() && file(it).exists() } == true &&
        !releaseKeystorePassword.isNullOrBlank() &&
        !releaseKeyAlias.isNullOrBlank()

